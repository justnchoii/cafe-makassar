function normalizeText(text) {
  return text
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9\s-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function hasAny(text, terms) {
  return terms.some(term => text.includes(term));
}

function getCafeAliases(cafe) {
  const normalizedName = normalizeText(cafe.name);
  const words = normalizedName
    .split(' ')
    .filter(word => word.length >= 4 && !cafeStopWords.has(word));

  const aliases = new Set([normalizedName]);
  words.forEach(word => aliases.add(word));

  for (let i = 0; i < words.length - 1; i += 1) {
    aliases.add(`${words[i]} ${words[i + 1]}`);
  }

  return [...aliases].filter(alias => alias.length >= 4);
}

function findMentionedCafes(message) {
  const normalizedMessage = normalizeText(message);
  const matches = [];

  for (const cafe of cafeData) {
    let bestAlias = '';
    for (const alias of getCafeAliases(cafe)) {
      if (normalizedMessage.includes(alias) && alias.length > bestAlias.length) {
        bestAlias = alias;
      }
    }

    if (bestAlias) {
      matches.push({ cafe, alias: bestAlias });
    }
  }

  return matches
    .sort((a, b) => b.alias.length - a.alias.length)
    .map(match => match.cafe);
}

function findAreaCafes(message) {
  const normalizedMessage = normalizeText(message);
  const area = areaKeywords.find(item => hasAny(normalizedMessage, item.terms));

  if (!area) {
    return null;
  }

  const cafes = cafeData.filter(cafe => hasAny(normalizeText(cafe.addr), area.terms));
  return cafes.length ? { area: area.label, cafes } : null;
}

function cleanDescription(description) {
  return description
    .replace(/^Cafe real dari link Google Maps yang kamu kirim\.?\s*/i, '')
    .replace(/^Cafe real /i, '')
    .replace(/^Cafe /i, '')
    .trim();
}

function getBestFor(cafe) {
  if (cafe.fac.includes('Sea View')) {
    return 'sunset, nongkrong santai, dan foto-foto';
  }

  if (cafe.cat === 'rooftop') {
    return 'sunset, dinner, dan nongkrong malam';
  }

  if (cafe.fac.includes('Workspace') || cafe.fac.includes('Meeting Room')) {
    return 'kerja, meeting, dan nongkrong lama';
  }

  if (cafe.cat === 'traditional') {
    return 'ngopi santai dan suasana klasik';
  }

  return 'nongkrong, ngopi, dan foto-foto';
}

function getVibeSentence(cafe) {
  if (cafe.fac.includes('Sea View')) {
    return 'Vibenya santai dengan view laut dan enak buat cari suasana sore atau sunset.';
  }

  if (cafe.cat === 'rooftop') {
    return 'Vibenya lebih premium dan cocok buat lihat view kota atau laut dari ketinggian.';
  }

  if (cafe.fac.includes('Workspace') || cafe.fac.includes('Meeting Room')) {
    return 'Vibenya nyaman buat duduk lama, kerja, atau meeting santai.';
  }

  if (cafe.cat === 'traditional') {
    return 'Vibenya klasik, sederhana, dan pas buat ngopi santai.';
  }

  return 'Vibenya modern, nyaman, dan enak buat nongkrong atau foto aesthetic.';
}

function getCafeSummary(cafe) {
  return `${cleanDescription(cafe.desc)}. ${getVibeSentence(cafe)}`;
}

function formatCafeLine(cafe, includeDesc = false) {
  const base = `• ${cafe.name} — ⭐${cafe.rating} (${cafe.price})\n  📍 ${cafe.addr}`;
  return includeDesc ? `${base}\n  ${cleanDescription(cafe.desc)}` : base;
}

function buildCafeDetailResponse(cafe, compact = false) {
  const header = `☕ ${cafe.name}`;
  const summary = getCafeSummary(cafe);
  const facilities = cafe.fac.slice(0, compact ? 3 : 4).join(', ');

  if (compact) {
    return `${header}\n${summary}\n⭐ ${cafe.rating}/5 • ${cafe.price}\n📍 ${cafe.addr}`;
  }

  return `${header}\n\n${summary}\n\n⭐ Rating: ${cafe.rating}/5\n📍 Lokasi: ${cafe.addr}\n🏷️ Tipe: ${categoryLabels[cafe.cat] || cafe.cat}\n✨ Cocok untuk: ${getBestFor(cafe)}\n🪑 Fasilitas utama: ${facilities}`;
}

function buildCafeIntentResponse(cafe, message, compact = false) {
  const normalizedMessage = normalizeText(message);

  if (hasAny(normalizedMessage, ['rating', 'bintang', 'star', 'nilai'])) {
    return compact
      ? `⭐ ${cafe.name} ratingnya ${cafe.rating}/5.`
      : `⭐ ${cafe.name} punya rating ${cafe.rating}/5.\n\nMenurut data web ini, tempatnya cocok buat ${getBestFor(cafe)}.`;
  }

  if (hasAny(normalizedMessage, ['alamat', 'lokasi', 'dimana', 'daerah'])) {
    return compact
      ? `📍 ${cafe.name} ada di ${cafe.addr}.`
      : `📍 Lokasi ${cafe.name} ada di ${cafe.addr}.\n\nKalau kamu mau, aku bisa bantu jelaskan juga suasana atau cocok buat apa.`;
  }

  if (hasAny(normalizedMessage, ['fasilitas', 'wifi', 'ac', 'parkir', 'indoor', 'outdoor'])) {
    const facilities = cafe.fac.join(', ');
    return compact
      ? `🪑 ${cafe.name}: ${facilities}.`
      : `🪑 Fasilitas utama di ${cafe.name}: ${facilities}.\n\nTempat ini paling cocok buat ${getBestFor(cafe)}.`;
  }

  if (hasAny(normalizedMessage, ['kerja', 'wfc', 'laptop', 'meeting', 'nongkrong', 'sunset', 'malam', 'foto', 'aesthetic'])) {
    return compact
      ? `✨ ${cafe.name} cocok buat ${getBestFor(cafe)}.`
      : `✨ ${cafe.name} paling cocok buat ${getBestFor(cafe)}.\n\n${getVibeSentence(cafe)}`;
  }

  if (hasAny(normalizedMessage, ['suasana', 'vibe', 'interior', 'tempat', 'bagus', 'gimana', 'bagaimana', 'worth it'])) {
    return compact
      ? `☕ ${cafe.name}: ${getVibeSentence(cafe)}`
      : `☕ Soal suasana, ${cafe.name} ${cleanDescription(cafe.desc)}.\n\n${getVibeSentence(cafe)}\n\nRatingnya ${cafe.rating}/5 jadi cukup menarik kalau kamu cari tempat buat ${getBestFor(cafe)}.`;
  }

  return buildCafeDetailResponse(cafe, compact);
}

