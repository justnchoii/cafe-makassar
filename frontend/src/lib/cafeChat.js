function getRelaxedSignature(text) {
  return normalizeText(text).replace(/\s+/g, '').replace(/[aeiou]/g, '');
}

function levenshteinDistance(a, b) {
  if (a === b) {
    return 0;
  }

  const rows = a.length + 1;
  const cols = b.length + 1;
  const matrix = Array.from({ length: rows }, () => Array(cols).fill(0));

  for (let i = 0; i < rows; i += 1) {
    matrix[i][0] = i;
  }

  for (let j = 0; j < cols; j += 1) {
    matrix[0][j] = j;
  }

  for (let i = 1; i < rows; i += 1) {
    for (let j = 1; j < cols; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      matrix[i][j] = Math.min(
        matrix[i - 1][j] + 1,
        matrix[i][j - 1] + 1,
        matrix[i - 1][j - 1] + cost
      );
    }
  }

  return matrix[a.length][b.length];
}

function getMessageTerms(message) {
  const words = normalizeText(message).split(' ').filter(Boolean);
  const terms = new Set(words);

  for (let i = 0; i < words.length - 1; i += 1) {
    terms.add(`${words[i]} ${words[i + 1]}`);
  }

  return [...terms];
}

function getAliasMatchScore(alias, normalizedMessage, messageTerms) {
  if (normalizedMessage.includes(alias)) {
    return 3;
  }

  const compactAlias = alias.replace(/\s+/g, '');
  if (compactAlias.length < 5) {
    return 0;
  }

  const aliasSignature = getRelaxedSignature(compactAlias);

  for (const term of messageTerms) {
    const compactTerm = term.replace(/\s+/g, '');

    if (compactTerm.length < 5) {
      continue;
    }

    if (compactTerm === compactAlias) {
      return 3;
    }

    if (aliasSignature && aliasSignature === getRelaxedSignature(compactTerm)) {
      return 2;
    }

    if (Math.abs(compactAlias.length - compactTerm.length) <= 2 && levenshteinDistance(compactAlias, compactTerm) <= 2) {
      return 1;
    }
  }

  return 0;
}

function getCafeAliases(cafe) {
  const normalizedName = normalizeText(cafe.name);
  const words = normalizedName
    .split(' ')
    .filter(word => word.length >= 4 && !cafeStopWords.has(word));

  const aliases = new Set([normalizedName]);
  words.forEach(word => aliases.add(word));

  for (let i = 0; i < words.length - 1; i += 1) {
    aliases.add(`${words[i]} ${words[i + 1]}`);
  }

  return [...aliases].filter(alias => alias.length >= 4);
}

function findMentionedCafes(message) {
  const normalizedMessage = normalizeText(message);
  const messageTerms = getMessageTerms(message);
  const matches = [];

  for (const cafe of cafeData) {
    let bestAlias = '';
    let bestScore = 0;

    for (const alias of getCafeAliases(cafe)) {
      const score = getAliasMatchScore(alias, normalizedMessage, messageTerms);

      if (score > bestScore || (score === bestScore && alias.length > bestAlias.length)) {
        bestAlias = alias;
        bestScore = score;
      }
    }

    if (bestAlias && bestScore > 0) {
      matches.push({ cafe, alias: bestAlias, score: bestScore });
    }
  }

  return matches
    .sort((a, b) => b.score - a.score || b.alias.length - a.alias.length)
    .map(match => match.cafe);
}

export function isCafeRelatedChatMessage(message, history = []) {
  const normalizedMessage = normalizeText(message);
  const historyText = Array.isArray(history)
    ? history
      .filter(item => item && typeof item.content === 'string')
      .map(item => item.content)
      .join(' ')
    : '';
  const normalizedHistory = normalizeText(historyText);
  const hasMessageTopic = hasCafeTopicKeyword(normalizedMessage);
  const hasMentionedCafe = findMentionedCafes(message).length > 0;
  const hasAreaMention = Boolean(findAreaCafes(message));
  const isFollowUp = hasAny(normalizedMessage, cafeFollowUpKeywords);
  const historyHasCafeContext = hasCafeTopicKeyword(normalizedHistory) || findMentionedCafes(historyText).length > 0;

  return hasMessageTopic || hasMentionedCafe || hasAreaMention || (isFollowUp && historyHasCafeContext);
}

function findAreaCafes(message) {
  const normalizedMessage = normalizeText(message);
  const area = areaKeywords.find(item => hasAny(normalizedMessage, item.terms));

  if (!area) {
    return null;
  }

  const cafes = cafeData.filter(cafe => hasAny(normalizeText(cafe.addr), area.terms));
  return cafes.length ? { area: area.label, cafes } : null;
}

function filterExcludedCafes(cafes, excludedCafeNames) {
  if (!excludedCafeNames?.length) {
    return cafes;
  }

  const excludedSet = new Set(excludedCafeNames);
  return cafes.filter(cafe => !excludedSet.has(cafe.name));
}

function rankCafes(cafes, scorer) {
  return [...cafes]
    .map(cafe => ({ cafe, score: scorer(cafe) }))
    .sort((a, b) => b.score - a.score || b.cafe.rating - a.cafe.rating)
    .map(item => item.cafe);
}

